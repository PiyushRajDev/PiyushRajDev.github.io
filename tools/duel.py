def esc(v: object) -> str:
    return html.escape(str(v), quote=True)


def channel(tag: str, attr: str, frames: list[tuple[float, str]], *,
            calc: str = "spline", typ: str | None = None,
            dur: float = DURATION, additive: str | None = None,
            splines: str | None = None, repeat: bool = True) -> str:
    """Emit an SVG animation element from absolute seconds in one master timeline."""
    if len(frames) < 2:
        raise ValueError(f"{attr}: at least two keyframes required")
    times = [t for t, _ in frames]
    if times != sorted(times) or len(times) != len(set(times)):
        raise ValueError(f"{attr}: keyframe times must be strictly increasing")
    if times[0] != 0 or abs(times[-1] - dur) > 1e-6:
        raise ValueError(f"{attr}: timeline must begin at 0 and end at duration")
    values = ";".join(esc(v) for _, v in frames)
    key_times = ";".join(f"{t / dur:.6f}" for t in times)
    attrs = [f'attributeName="{attr}"', f'dur="{dur:g}s"',
             f'values="{values}"', f'keyTimes="{key_times}"',
             f'calcMode="{calc}"']
    if tag == "animateTransform":
        if not typ:
            raise ValueError("animateTransform requires type")
        attrs.append(f'type="{typ}"')
    if additive:
        attrs.append(f' additive="{additive}"')
    if calc == "spline":
        if splines is None:
            splines = ";".join(["0.42 0 0.58 1"] * (len(frames) - 1))
        if len(splines.split(";")) != len(frames) - 1:
            raise ValueError(f"{attr}: need one spline per keyframe interval")
        attrs.append(f'keySplines="{splines}"')
    if repeat:
        attrs.append('repeatCount="indefinite"')
    return f"<{tag} {' '.join(attrs)}/>"


def anim(attr: str, frames: list[tuple[float, str]], **kw: object) -> str:
    return channel("animate", attr, frames, **kw)


def move(frames: list[tuple[float, str]], **kw: object) -> str:
    return channel("animateTransform", "transform", frames, typ="translate", **kw)


def rotate(frames: list[tuple[float, str]], **kw: object) -> str:
    kw.setdefault("additive", "sum")
    return channel("animateTransform", "transform", frames, typ="rotate", **kw)


def scale(frames: list[tuple[float, str]], **kw: object) -> str:
    return channel("animateTransform", "transform", frames, typ="scale", **kw)


def opacity(frames: list[tuple[float, str]], **kw: object) -> str:
    return anim("opacity", frames, calc="discrete", **kw)


