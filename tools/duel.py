def validate(svg: str) -> None:
    """Fail the build on malformed XML, duplicate IDs, broken refs or bad timelines."""
    from xml.etree import ElementTree as ET
    root = ET.fromstring(svg)
    ids = [node.get("id") for node in root.iter() if node.get("id")]
    duplicates = sorted({item for item in ids if ids.count(item) > 1})
    if duplicates:
        raise ValueError(f"Duplicate SVG IDs: {duplicates}")
    for node in root.iter():
        if node.tag.rsplit("}", 1)[-1] not in {"animate", "animateTransform"}:
            continue
        values = node.get("values")
        key_times = node.get("keyTimes")
        if not values or not key_times:
            continue
        v = values.split(";")
        kt = [float(part) for part in key_times.split(";")]
        if len(v) != len(kt):
            raise ValueError(f"{node.get('attributeName')}: values/keyTimes length mismatch")
        if abs(kt[0]) > 1e-6 or abs(kt[-1] - 1) > 1e-6:
            raise ValueError(f"{node.get('attributeName')}: keyTimes must span 0..1")
        if any(right <= left for left, right in zip(kt, kt[1:])):
            raise ValueError(f"{node.get('attributeName')}: keyTimes must be strictly increasing")
    # lxml XPath above reads whole attribute strings; verify every url(#id) target.
    import re
    for ref in re.findall(r"url\(#([^)]+)\)", svg):
        if ref not in ids:
            raise ValueError(f"Missing SVG reference target: #{ref}")


